    private void cargarCampos() {
        
        //Llenando JTextField en vez de JLabel
        File archivo = new File("src\\main\\UsuariosRegistrados\\" + usuarioActual + ".txt");
        try {
            BufferedReader reader = new BufferedReader(new FileReader(archivo));
            String linea;
            while ((linea = reader.readLine()) != null) {
                if (linea.startsWith("Sobre mi: "))
                    txtSobreMi.setText(linea.replace("Sobre mi: ", "").trim());
                if (linea.startsWith("Universidad: "))
                    txtUniversidad.setText(linea.replace("Universidad: ", "").trim());
                if (linea.startsWith("Carrera: "))
                    txtCarrera.setText(linea.replace("Carrera: ", "").trim());
                if (linea.startsWith("Habilidades: "))
                    txtHabilidades.setText(linea.replace("Habilidades: ", "").trim());
                if (linea.startsWith("Colegio: "))
                    txtColegio.setText(linea.replace("Colegio: ", "").trim());
            }
            reader.close();
        } catch (IOException e) { e.printStackTrace(); }
        
    }
    
