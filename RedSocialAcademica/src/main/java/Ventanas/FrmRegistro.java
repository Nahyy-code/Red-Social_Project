    private void CrearUsuario()
    {
        String usuario= txtUsuario.getText().trim();
        String TipodeUsuario = rdEstudiante.isSelected() ? "Estudiante" : "Docente"; //seleccion de rol
        String Genero= cbGenero.getSelectedItem().toString();
        
        //creacion de carpeta (si no hay)
        String rutaCarpeta= "src\\main\\UsuariosRegistrados";
        File CarpetaUsuarios = new File (rutaCarpeta);
        if (!CarpetaUsuarios.exists()) CarpetaUsuarios.mkdir();
        
        String foto = rutaFotoSeleccionada.isEmpty() ? "profileDefault.png" : usuario + rutaFotoSeleccionada.substring(rutaFotoSeleccionada.lastIndexOf("."));
         
        //Creacion de usuario(archivo)
        File IdUsuario = new File(CarpetaUsuarios,usuario+ ".txt");
        try(FileWriter writer = new FileWriter(IdUsuario)){
            writer.write("DATOS DEL USUARIO \n");
            writer.write("Usuario: @"+txtUsuario.getText() + "\n");
            writer.write("Nombre: "+txtNombre.getText() + "\n");
            writer.write("Apellido: "+txtApellido.getText() + "\n");
            writer.write("Correo: "+txtCorreo.getText() + "\n");
            writer.write("Contraseña: "+String.valueOf(txtContraseña.getPassword())+ "\n");
            writer.write("Genero: "+Genero+ "\n");
            writer.write("Tipo de Usuario: "+TipodeUsuario+ "\n");
            writer.write ("Foto: " +foto+ "\n");
            writer.write("Edad: \n");
            writer.write("Sobre mi: \n");
            writer.write("Universidad: \n");
            writer.write("Facultad: \n");
            writer.write("Carrera: \n");
            writer.write("Habilidades: \n");
            writer.write("Colegio: \n");
            
            writer.write("Rol: Gratuito\n");
            
            writer.close();
            
            guardarFoto(usuario);
        
            JOptionPane.showMessageDialog(null, "Usuario Registrado \nVuelva a Iniciar Sesion");
            
        }catch(IOException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error al registrar el usuario en el sistema.");
        }        
    }
    
