    /* Lee la línea "Amigos: " de un archivo y devuelve la lista de nombres
       separados por comas, Si no existe la línea, devuelve una lista vacía.
    */
    private ArrayList<String> leerAmigos(File archivoUsuario) {
        ArrayList<String> amigos = new ArrayList<>();
        
        if(!archivoUsuario.exists()) {
            return amigos;
        }
        
        try(BufferedReader lector = new BufferedReader(new FileReader(archivoUsuario))) {
            String linea = lector.readLine();
            while(linea != null) {
                if(linea.startsWith("Amigos: ")) {
                    String contenido = linea.replace("Amigos: ", "").trim();
                    if(!contenido.isEmpty()) {
                        String[] partes = contenido.split(",");
                        for(int i = 0; i < partes.length; i++) {
                            amigos.add(partes[i].trim());
                        }
                    }
                }
                linea = lector.readLine();                
            }
                    
        } catch(IOException e) {
            System.out.println("No se pudo leer la lista de amigos.");
        }
        return amigos;
    }
    
    /* Carga imagen desde carpeta fotos de perfil
       Si no la encuentra, usa profileDefault.png como respaldo.
    */
    private ImageIcon cargarFotoRedimensionada(String nombreArchivoFoto, int ancho, int alto) {
        File archivoFoto = new File(RUTA_FOTOS + nombreArchivoFoto);
        
        if(!archivoFoto.exists()) {
            archivoFoto = new File(RUTA_FOTOS + "profileDefault.png");
        }
        
        ImageIcon original = new ImageIcon(archivoFoto.getAbsolutePath());
        Image escalada = original.getImage().getScaledInstance(ancho, alto, Image.SCALE_SMOOTH);
        return new ImageIcon(escalada);
    }
    
    private boolean contieneIgnorandoMayus(ArrayList<String> lista, String nombre) {
        
        for(int i = 0; i < lista.size(); i++) {
            
            if(lista.get(i).equalsIgnoreCase(nombre)) {
                return true;
            }
        }
        return false;
    }
    
    /* Agregar un nombre al linea "Amigos: " de un archivo específico.
       Si la línea no existe todavía, la crea al final del archivo. 
    */
    private void agregarAmigoEnArchivo(File archivo, String nombreAgregar) {
        
        ArrayList<String> lineas = new ArrayList<>();
        boolean lineaAmigosEncontrada = false;
        
        try(BufferedReader lector = new BufferedReader(new FileReader(archivo))) {
            
            String linea = lector.readLine();
            while(linea != null) {
                
                if(linea.startsWith("Amigos: ")) {
                    lineaAmigosEncontrada = true;
                    
                    ArrayList<String> amigosActuales = leerAmigos(archivo);
                    if(!contieneIgnorandoMayus(amigosActuales, nombreAgregar)) {
                        amigosActuales.add(nombreAgregar);
                    }
                    
                    StringBuilder nuevaLinea = new StringBuilder("Amigos: ");
                    for(int i = 0; i < amigosActuales.size(); i++) {
                        nuevaLinea.append(amigosActuales.get(i));
                        if(i < amigosActuales.size() - 1) {
                            nuevaLinea.append(", ");
                        }
                    }
                    
                    lineas.add(nuevaLinea.toString());
                } else {
                    
                    lineas.add(linea);
                }
                
                linea = lector.readLine();
            }
            
        } catch(IOException e) {
            
            System.out.println("No se pudo leer: " + archivo.getName());
            return;
        }
        
        /* Si el archivo no tenía linea de "Amigos: ", la agregarmos al final */
        if(!lineaAmigosEncontrada) {
            lineas.add("Amigos: " + nombreAgregar);
        }
        
        try(FileWriter escritor = new FileWriter(archivo)) {
            for(int i = 0; i < lineas.size(); i++) {
                escritor.write(lineas.get(i) + "\n");
            }
        } catch(IOException e) {
            System.out.println("No se pudo guardar " + archivo.getName());
        }
    }
    
    /* Agregar Usuario A a la lista de amigos de Usuario B, y
       agrega  Usuario B a la lista de amigos de Usuario A.
       Así la amistad será mutua en ambos archivos .txt.
    */
    private void agregarAmigoMutuo(String usuarioBase, String usuarioNuevo) {
        agregarAmigoEnArchivo(new File(RUTA_USUARIOS + usuarioBase + ".txt"), usuarioNuevo);
        agregarAmigoEnArchivo(new File(RUTA_USUARIOS + usuarioNuevo + ".txt"), usuarioBase);
    }
    
     /* Lee los archivos de un usuario los datos: Nombre, Apellido y Foto.
        Arma una fila visual con foto + nombre + agregar botón.
    */
    private void agregarFilaResultado(File archivoUsuario, String nombreUsuario, ArrayList<String> misAmigos) {
        
        String nombre = "";
        String apellido = "";
        String foto = "profileDefault.png";
        
        try(BufferedReader lector = new BufferedReader(new FileReader(archivoUsuario))) {
            String linea = lector.readLine();
            while(linea != null) {
                if(linea.startsWith("Nombre: ")) {
                    nombre = linea.replace("Nombre: ", "").trim();
                }
                if(linea.startsWith("Apellido: ")) {
                    apellido = linea.replace("Apellido: ", "").trim();
                }
                if(linea.startsWith("Foto: ")) {
                    foto = linea.replace("Foto: ", "").trim();
                }
                linea = lector.readLine();
            }
            
        } catch(IOException e) {
            System.out.println("No se pudo leer: " + archivoUsuario.getName());
        }
        
        /* Fila visual */
        JPanel fila = new JPanel();
        fila.setBackground(new Color(13,20,38));
        fila.setLayout(new BoxLayout(fila, BoxLayout.X_AXIS));
        fila.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createEmptyBorder(8,0,8,0),
                BorderFactory.createEmptyBorder(10,15,10,15)));
        fila.setMaximumSize(new Dimension(Integer.MAX_VALUE, 70));
        fila.setAlignmentX(Component.LEFT_ALIGNMENT);
        
        /* Foto Perfil */
        JLabel lblFoto = new JLabel();
        ImageIcon icono = cargarFotoRedimensionada(foto,45,45);
        lblFoto.setIcon(icono);
        lblFoto.setPreferredSize(new Dimension(45,45));
        
        /* Nombre de usuario + nombre completo. */
        JPanel pnlTexto = new JPanel();
        pnlTexto.setBackground(fila.getBackground());
        pnlTexto.setLayout(new BoxLayout(pnlTexto, BoxLayout.Y_AXIS));
        pnlTexto.setBorder(BorderFactory.createEmptyBorder(0,12,0,0));
        
        JLabel lblUsuario = new JLabel("@" + nombreUsuario);
        lblUsuario.setForeground(new Color(232,244,253));
        lblUsuario.setFont(new Font("Segoe UI", Font.BOLD, 13));
        
        JLabel lblNombreCompleto = new JLabel(nombre + " " + apellido);
        lblNombreCompleto.setForeground(new Color(107,138,170));
        lblNombreCompleto.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        
        pnlTexto.add(lblUsuario);
        pnlTexto.add(lblNombreCompleto);
        
        /* Boton agregar / Ya son amigos */
        JButton btnAgregar = new JButton();
        btnAgregar.setFocusPainted(false);
        btnAgregar.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        
        boolean yaEsAmigo = contieneIgnorandoMayus(misAmigos, nombreUsuario);
        
        if(yaEsAmigo) {
            btnAgregar.setText("Ya son amigos");
            btnAgregar.setEnabled(false);
            btnAgregar.setBackground(new Color(40,50,70));
            btnAgregar.setForeground(new Color(107,138,170));
        } else {
            btnAgregar.setText("Agregar");
            btnAgregar.setBackground(new Color(37,99,235));
            btnAgregar.setForeground(new Color(232,244,253));
            btnAgregar.setCursor(new Cursor(Cursor.HAND_CURSOR));
            btnAgregar.addActionListener(e -> {
                agregarAmigoMutuo(Sesion.usuarioActual, nombreUsuario);
                btnAgregar.setText("Ya son amigos");
                btnAgregar.setEnabled(false);
                btnAgregar.setBackground(new Color(40,50,70));
                btnAgregar.setForeground(new Color(107,138,170));
                JOptionPane.showMessageDialog(this, "Ahora son amigos con @" + nombreUsuario);
            });
        }
        
        fila.add(lblFoto);
        fila.add(pnlTexto);
        fila.add(Box.createHorizontalGlue());
        fila.add(btnAgregar);
        
        pnlResultados.add(fila);
        pnlResultados.add(Box.createVerticalStrut(8));
    }
    
    /* Busca usuarios cuyo nombre de usuario contenga el texto escrito
       (sin distinguir mayus/minus) y arma una fila por cada uno. 
    */
    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String textoBusqueda = txtBuscar.getText().trim().toLowerCase();
        pnlResultados.removeAll(); /*Limpia resultados anteriores*/
        
        if(textoBusqueda.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe un nombre de usuario para buscar.");
            return;
        }
        
        File carpetaUsuarios = new File(RUTA_USUARIOS);
        File[] archivos = carpetaUsuarios.listFiles();
        
        /*Leer mi propia lista de amigos para saber a quién ya agregé*/
        ArrayList<String> misAmigos = leerAmigos(new File(RUTA_USUARIOS + Sesion.usuarioActual + ".txt"));
        
        boolean huboResultados = false;
        
        if(archivos != null) {
            for (int i = 0; i < archivos.length; i++) {
                
                File archivo = archivos[i];
                
                if(!archivo.getName().endsWith(".txt")) {
                    continue;
                }
                /* El nombre del archivo (sin .txt) es el nombre de usuario */
                String nombreUsuarioArchivo = archivo.getName().replace(".txt", "");
                
                /* No mostrarse a si mismo en los resultados */
                if(nombreUsuarioArchivo.equalsIgnoreCase(Sesion.usuarioActual)) {
                    continue;
                }
                
                if(nombreUsuarioArchivo.toLowerCase().contains(textoBusqueda)) {
                    agregarFilaResultado(archivo, nombreUsuarioArchivo, misAmigos);
                    huboResultados = true;
                }
            }
        }
        
        if(!huboResultados) {
            lblSinResultados.setIcon(new ImageIcon(getClass().getResource("/Imgs_S/iconExclamationMark-48.png")));
            lblSinResultados.setText("NO SE ENCONTRARON USUARIOS.");
            pnlResultados.add(lblSinResultados);
            
        }
        
        pnlResultados.revalidate();
        pnlResultados.repaint();
    }//GEN-LAST:event_btnBuscarActionPerformed

