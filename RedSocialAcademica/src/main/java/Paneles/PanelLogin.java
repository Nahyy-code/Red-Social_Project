    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        String usuario = txtUsuario.getText().trim();
        String contraseña = new String(txtContraseña.getPassword());
        
        if(usuario.isEmpty() || contraseña.isEmpty()){
            JOptionPane.showMessageDialog(this, "Completa todos los campos.");
            return;
        }
        File archivo = new File(RUTA + usuario + ".txt");
        if(!archivo.exists()){
            JOptionPane.showMessageDialog(this, "Usuario no encontrado");
            return;
        }
        try(BufferedReader br = new BufferedReader(new FileReader(archivo))){
            br.readLine();
            br.readLine();
            br.readLine();
            br.readLine();
            br.readLine();
            String lineaContraseña = br.readLine();
            
            if(lineaContraseña == null){
                JOptionPane.showMessageDialog(this, "Archivo de usuario corrupto.");
                return;
            }
            
            String contraseñaGuardada = lineaContraseña.replace("Contraseña: ", "").trim();
            
            if(contraseña.equals(contraseñaGuardada)){
                JOptionPane.showMessageDialog(this, "¡Bienvenido, @"+usuario+"!");
            } else {
                JOptionPane.showMessageDialog(this, "Contraseña incorrecta.");
            }
            
        } catch (IOException ex){
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al aleer el archivo.");
        }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

