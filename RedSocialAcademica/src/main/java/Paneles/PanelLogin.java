    private void btnMostrarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarSesionActionPerformed
        // TODO add your handling code here:
        ImageIcon mostrar = new ImageIcon(getClass().getResource("/Imgs/mostrar.png"));
        ImageIcon ocultar = new ImageIcon(getClass().getResource("/Imgs/ocultar.png"));
        if(btnMostrarSesion.isSelected()){
            txtContraseña.setEchoChar((char)0);
            btnMostrarSesion.setIcon(ocultar);
        } else {
            txtContraseña.setEchoChar('•');
            btnMostrarSesion.setIcon(mostrar);
        }
        
    }//GEN-LAST:event_btnMostrarSesionActionPerformed


