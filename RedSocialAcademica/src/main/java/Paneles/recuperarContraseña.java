    public void restablecer(){
        String correo = txtCorreo.getText().trim();
        String nueva = new String(txtNueva.getPassword());
        String confirmar = new String(txtConfirmar.getPassword());
        
        lblErrorCorreo.setVisible(false);
        lblErrorContraseña.setVisible(false);
        
        if(correo.isEmpty()||nueva.isEmpty()||confirmar.isEmpty()){
          JOptionPane.showMessageDialog(this,  "Completa todos los campos.");
          return;
        }
        if(!nueva.equals(confirmar)){
            lblErrorContraseña.setText("Las contraseñas no coinciden.");
            lblErrorContraseña.setVisible(true);
            return;
        }
        //Buscar el correo en los archivos .txt
        java.io.File carpeta = new java.io.File("src\\main\\UsuariosRegistrados");
        java.io.File[] archivos;
        archivos = carpeta.listFiles(new java.io.FilenameFilter() {
            @Override
            public boolean accept(File dir, String nombre) {
                return nombre.endsWith(".txt");
            }
        });
            
        if(archivos == null || archivos.length == 0){
            lblErrorCorreo.setVisible(true);
            return;
        }
        
        java.io.File archivoEncontrado = null;
        
        for(java.io.File archivo : archivos){
            try(java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo)))
            {
                 br.readLine();
                 br.readLine();
                 br.readLine();
                 br.readLine();
                String lineaCorreo = br.readLine();
                if(lineaCorreo != null){
                    String correoGuardado = lineaCorreo.replace("Correo: ", "").trim();
                    if(correoGuardado.equalsIgnoreCase(correo)){
                        archivoEncontrado = archivo;
                        break;
                    }
                    
                }
            } catch(java.io.IOException ex){
                ex.printStackTrace();
            }    
        }
        if(archivoEncontrado == null){
            lblErrorCorreo.setVisible(true);
            return;
        }
        
        try{
            String l1,l2,l3,l4,l5,l7;            
            try (java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivoEncontrado))) {
                l1 = br.readLine();
                l2 = br.readLine();
                l3 = br.readLine();
                l4 = br.readLine();
                l5 = br.readLine();
                br.readLine();
                l7 = br.readLine();
            }
           
            try (java.io.BufferedWriter bw = new java.io.BufferedWriter(new java.io.FileWriter(archivoEncontrado))) {
                bw.write(l1 != null ? l1 : ""); bw.newLine();
                bw.write(l2 != null ? l2 : ""); bw.newLine();
                bw.write(l3 != null ? l3 : ""); bw.newLine();
                bw.write(l4 != null ? l4 : ""); bw.newLine();
                bw.write(l5 != null ? l5 : ""); bw.newLine();
                bw.write("Contraseña: " + nueva); bw.newLine();
                bw.write(l7 != null ? l7 : ""); bw.newLine();
            }
           
           JOptionPane.showMessageDialog(this, "¡Contraseña restablecida con éxito!");
           limpiarCampos();
           frame.mostrarPanel("login");
        } catch(java.io.IOException ex){
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error al actualizar el archivo");
        }
    }
    
